"""
Tiny CPU smoke training run for B0 / B1 / B2 (~30 steps each).

Data: synthetic random-token sequences with learnable structure — each sequence
is generated by iterating a fixed random permutation of the vocab
(x_{t+1} = perm[x_t]), starting from a random token. Pure uniform-random tokens
would be unlearnable (optimal loss = ln V forever), so this deterministic
first-order structure is the minimal change that lets loss actually decrease;
the tokens themselves are still random draws.

Optimizer: plan section 2B locked settings — AdamW, beta1=0.9, beta2=0.95,
weight decay 0.1, grad clip 1.0. LR 3e-3 constant (the plan's cosine schedule
and 3-point sweep are for real Tier runs, not a 30-step smoke test).
"""

import torch
import torch.nn.functional as F

from model import LoopConfig, build

CFG = LoopConfig(d=128, d_ff=352, L_pre=1, L_core=2, L_post=1, vocab_size=256, N=2)
STEPS, BATCH, SEQ = 30, 32, 48
LR = 3e-3


def make_batch(perm, g):
    starts = torch.randint(0, CFG.vocab_size, (BATCH, 1), generator=g)
    seq = [starts]
    for _ in range(SEQ - 1):
        seq.append(perm[seq[-1]])
    return torch.cat(seq, dim=1)


def train(name):
    torch.manual_seed(42)
    model = build(name, CFG)
    opt = torch.optim.AdamW(model.parameters(), lr=LR, betas=(0.9, 0.95), weight_decay=0.1)
    g = torch.Generator().manual_seed(123)
    perm = torch.randperm(CFG.vocab_size, generator=g)
    losses = []
    for step in range(STEPS):
        ids = make_batch(perm, g)
        logits = model(ids[:, :-1])
        loss = F.cross_entropy(logits.reshape(-1, CFG.vocab_size), ids[:, 1:].reshape(-1))
        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        losses.append(loss.item())
    start = sum(losses[:3]) / 3
    end = sum(losses[-3:]) / 3
    print(f"{name}: step0 loss {losses[0]:.4f} | mean(first3) {start:.4f} -> "
          f"mean(last3) {end:.4f} | {'DECREASED' if end < start else 'NOT DECREASED'}")
    return start, end


if __name__ == "__main__":
    print(f"smoke train: {STEPS} steps, batch {BATCH}, seq {SEQ}, config "
          f"d={CFG.d} L={CFG.L_pre}/{CFG.L_core}/{CFG.L_post} N={CFG.N} V={CFG.vocab_size}")
    ok = True
    for name in ("B0", "B1", "B2"):
        s, e = train(name)
        ok = ok and e < s
    print("SMOKE TRAIN:", "PASS (all losses decreased)" if ok else "FAIL")
